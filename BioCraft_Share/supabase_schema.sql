create table if not exists public.tally_invoices (
  id bigint generated by default as identity primary key,
  invoice_key text not null unique,
  customer_name text not null,
  invoice_number text not null,
  phone_number text,
  amount_due numeric not null default 0,
  due_date text,
  payment_status text not null default 'pending',
  payment_state text not null default 'pending',
  payment_mode text,
  promised_pay_date text,
  payment_date text,
  dispute_reason text,
  last_call_id text,
  last_transcript text,
  last_recording text,
  source text not null default 'tally',
  tally_closed boolean not null default false,
  tally_synced_at timestamptz,
  updated_at timestamptz not null default now()
);
