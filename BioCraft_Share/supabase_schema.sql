create table if not exists public.call_logs (
  id uuid primary key default gen_random_uuid(),
  call_id text not null unique,
  invoice_id bigint,
  customer_name text,
  phone_number text,
  amount_due numeric,
  due_date text,
  trigger_source text default 'manual',
  call_status text default 'calling',
  outcome text,
  payment_state text default 'pending',
  payment_mode text,
  promised_pay_date text,
  payment_date text,
  dispute_reason text,
  transcript text,
  recording_url text,
  called_at timestamptz not null default now(),
  completed_at timestamptz,
  updated_at timestamptz not null default now()
);
alter table public.call_logs add column if not exists payment_state text default 'pending';
alter table public.call_logs add column if not exists payment_mode text;
alter table public.call_logs add column if not exists payment_date text;
create index if not exists call_logs_called_at_idx on public.call_logs(called_at desc);
create index if not exists call_logs_customer_idx on public.call_logs(lower(customer_name));
create index if not exists call_logs_invoice_idx on public.call_logs(invoice_id);
alter table public.call_logs enable row level security;
