create extension if not exists pgcrypto;

-- 1. Columns the existing code already uses but supabase_schema.sql never created ----------
alter table public.tally_invoices add column if not exists tally_synced_at_ist text;
alter table public.tally_invoices add column if not exists sync_batch_id text;
-- 2. New columns -------------------------------------------------------------------------------
alter table public.tally_invoices add column if not exists last_call_at timestamptz;
alter table public.tally_invoices add column if not exists tally_company text;
alter table public.tally_invoices add column if not exists legacy_sqlite_id bigint;
create unique index if not exists tally_invoices_legacy_sqlite_id_uidx
  on public.tally_invoices(legacy_sqlite_id) where legacy_sqlite_id is not null;
create index if not exists tally_invoices_last_call_id_idx on public.tally_invoices(last_call_id);
create index if not exists tally_invoices_promised_idx on public.tally_invoices(promised_pay_date);

-- Remember the ORIGINAL call_logs.invoice_id (the old SQLite id) so the migration can be rolled back.
alter table public.call_logs add column if not exists legacy_invoice_id bigint;
update public.call_logs set legacy_invoice_id = invoice_id
  where legacy_invoice_id is null and invoice_id is not null;

-- 3. Follow-up attempts (replaces the SQLite table; UNIQUE = the duplicate-call lock) ----------
create table if not exists public.followup_attempts (
  id bigint generated by default as identity primary key,
  invoice_id bigint not null,
  attempt_date text not null,
  slot text not null default 'morning',
  status text not null default 'starting',
  execution_id text,
  error_message text,
  created_at timestamptz not null default now(),
  constraint followup_attempts_one_per_slot unique (invoice_id, attempt_date, slot)
);
alter table public.followup_attempts enable row level security;

-- 4. Tally synchronisation log ------------------------------------------------------------------
create table if not exists public.tally_sync_log (
  id bigint generated by default as identity primary key,
  batch_id text not null unique,
  trigger text,
  status text not null default 'running',   -- running | success | warning | partial | failed
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  tally_company text,
  invoices_received integer,
  invoices_written integer,
  invoices_closed integer,
  invoices_reopened integer,
  warnings text,
  error text,
  agent_host text
);
create index if not exists tally_sync_log_started_idx on public.tally_sync_log(started_at desc);
alter table public.tally_sync_log enable row level security;

-- 5. Audit of invoices closed because they disappeared from a complete Tally export -------------
create table if not exists public.tally_close_audit (
  id bigint generated by default as identity primary key,
  batch_id text not null,
  invoice_id bigint,
  invoice_key text,
  previous_status text,
  previous_state text,
  closed_at timestamptz not null default now()
);
alter table public.tally_close_audit enable row level security;

-- 6. Safe reopen/close function -------------------------------------------------------------------
-- Called by the sync agent AFTER every chunk of a run was uploaded. Never deletes anything.
--  * Invoices that are in this batch and were closed earlier are reopened (Tally says: outstanding again).
--  * Unless p_reopen_only, open Tally invoices that are NOT in this batch are marked paid/closed,
--    every one is written to tally_close_audit, and nothing is closed if it would close an
--    unusually large share (more than max(5, 50% of open invoices)) unless p_force = true.
create or replace function public.tally_close_missing(
  p_batch text,
  p_company text default null,
  p_force boolean default false,
  p_reopen_only boolean default false
) returns jsonb
language plpgsql
as $$
declare
  v_seen int;
  v_open int;
  v_gone int;
  v_reopened int := 0;
  v_closed int := 0;
begin
  select count(*) into v_seen from public.tally_invoices where sync_batch_id = p_batch;
  if v_seen = 0 then
    return jsonb_build_object('closed', 0, 'reopened', 0, 'skipped_reason', 'batch has no invoices');
  end if;

  with r as (
    update public.tally_invoices
       set tally_closed = false, payment_state = 'pending', payment_status = 'pending', updated_at = now()
     where sync_batch_id = p_batch and tally_closed = true
     returning 1)
  select count(*) into v_reopened from r;

  if p_reopen_only then
    return jsonb_build_object('closed', 0, 'reopened', v_reopened, 'skipped_reason', 'snapshot not complete; reopen only');
  end if;

  select count(*) into v_open from public.tally_invoices
   where source = 'tally' and coalesce(tally_closed, false) = false
     and coalesce(payment_state, 'pending') <> 'done'
     and (p_company is null or tally_company is null or tally_company = p_company);

  select count(*) into v_gone from public.tally_invoices
   where source = 'tally' and coalesce(tally_closed, false) = false
     and coalesce(payment_state, 'pending') <> 'done'
     and (p_company is null or tally_company is null or tally_company = p_company)
     and coalesce(sync_batch_id, '') <> p_batch;

  if not p_force and v_gone > greatest(5, floor(v_open * 0.5)) then
    return jsonb_build_object('closed', 0, 'reopened', v_reopened, 'skipped_reason',
      format('would mark %s of %s open invoices as paid; looks wrong, so none were changed (run the agent with --force if it is right)', v_gone, v_open));
  end if;

  insert into public.tally_close_audit (batch_id, invoice_id, invoice_key, previous_status, previous_state)
  select p_batch, id, invoice_key, payment_status, payment_state from public.tally_invoices
   where source = 'tally' and coalesce(tally_closed, false) = false
     and coalesce(payment_state, 'pending') <> 'done'
     and (p_company is null or tally_company is null or tally_company = p_company)
     and coalesce(sync_batch_id, '') <> p_batch;

  with c as (
    update public.tally_invoices
       set payment_state = 'done', tally_closed = true, updated_at = now(),
           payment_status = case when lower(coalesce(payment_status, '')) in ('paid', 'paid_on_call', 'payment done', 'payment_done')
                                 then payment_status else 'paid' end
     where source = 'tally' and coalesce(tally_closed, false) = false
       and coalesce(payment_state, 'pending') <> 'done'
       and (p_company is null or tally_company is null or tally_company = p_company)
       and coalesce(sync_batch_id, '') <> p_batch
     returning 1)
  select count(*) into v_closed from c;

  return jsonb_build_object('closed', v_closed, 'reopened', v_reopened, 'skipped_reason', null);
end;
$$;

revoke all on function public.tally_close_missing(text, text, boolean, boolean) from public, anon, authenticated;
grant execute on function public.tally_close_missing(text, text, boolean, boolean) to service_role;
